    /**
     * Esta clase hereda de la clase MouseMotionAdapter que permite manejar eventos de
     * del mouse (mover el mouse; arrastrar y soltar).
     * Se la usa en el sistema para mostrar el ToolTipText adecuado en la cabecera de
     * las columnas. Es necesario hacerlo porque el ancho de las columnas a veces
     * resulta muy corto para mostrar leyendas que requieren más espacio.
     */
    private class ZafMouMotAda extends java.awt.event.MouseMotionAdapter
    {
        public void mouseMoved(java.awt.event.MouseEvent evt)
        {
            int intCol=tblDat.columnAtPoint(evt.getPoint());
            String strMsg="";
            switch (intCol)
            {
                case INT_TBL_DAT_LIN:
                    strMsg="";
                    break;
                case INT_TBL_DAT_CHK:
                    strMsg="";
                    break;
                case INT_TBL_DAT_USU:
                    strMsg="Usuario";
                    break;
                case INT_TBL_DAT_IDE:
                    strMsg="Identificador";
                    break;
                case INT_TBL_DAT_FEC_CRE:
                    strMsg="Fecha de Creacion";
                    break;
                case INT_TBL_DAT_FEC_MOD:
                    strMsg="Fecha de Modificacion";
                    break;        
                case INT_TBL_DAT_COD_USR:
                    strMsg="Usuario";
                    break;
                case INT_TBL_DAT_COD_IDE:
                    strMsg="Codigo Identificador";
                    break;                    
                default:
                    strMsg="";
                    break;
            }
            tblDat.getTableHeader().setToolTipText(strMsg);
        }
    }
    
