private boolean cargarConf()
    {
        int i, intNumCol;
        boolean blnRes=true;
        int contador =0;
        String strSQL ="";
        java.sql.Connection conLoc; 
        java.sql.Statement stmLoc;
        java.sql.ResultSet rstLoc;        
        try
        {
            conLoc=DriverManager.getConnection(objParSis.getStringConexion_Dynamics2021(), objParSis.getUsuarioBaseDatos_Dynamics2021(), objParSis.getClaveBaseDatos_Dynamics2021());      
            if (conLoc!=null)
            {
                stmLoc=conLoc.createStatement();
                strSQL="";       
                strSQL+=" SELECT  usr.tx_usr, trim (conf.tx_deside) as ident, conf.fe_ing,conf.fe_ultmod ,conf.co_usrIng  ,conf.co_ide  \n";
                strSQL+=" FROM  Dynamics2021.dbo.tbm_cabexpcol as conf \n";
                //strSQL+=" WHERE co_mnu = "+co_mnu +"\n";
                strSQL+="       inner join tbm_usr as usr on (conf.co_usrIng = usr.co_usr)\n";
                strSQL+=" WHERE conf.st_reg ='A' \n";                
                strSQL+=" ORDER BY conf.tx_deside ASC ";                  
                rstLoc=stmLoc.executeQuery(strSQL);   
                vecDat.clear();
                while (rstLoc.next())
                {
                    vecReg=new Vector();
                    vecReg.add(INT_TBL_DAT_LIN,"");
                    vecReg.add(INT_TBL_DAT_CHK,false);
                    vecReg.add(INT_TBL_DAT_USU,rstLoc.getString("tx_usr"));
                    vecReg.add(INT_TBL_DAT_IDE,rstLoc.getString("ident"));
                    vecReg.add(INT_TBL_DAT_FEC_CRE,rstLoc.getString("fe_ing"));
                    vecReg.add(INT_TBL_DAT_FEC_MOD,rstLoc.getString("fe_ultmod"));
                    vecReg.add(INT_TBL_DAT_COD_USR,rstLoc.getString("co_usrIng"));
                    vecReg.add(INT_TBL_DAT_COD_IDE,rstLoc.getString("co_ide"));
                    vecDat.add(vecReg);
                }
            }
            
            rstLoc=null;
            stmLoc=null;
            conLoc.close();
            conLoc=null;                            
            objTblMod.setData(vecDat);
            tblDat.setModel(objTblMod);
            //Limpiar vector de datos.
            vecDat.clear();
        }
        catch (Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }


    
    



