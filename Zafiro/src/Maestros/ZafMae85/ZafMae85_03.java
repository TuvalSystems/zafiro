    private boolean consultar_Grupo(java.sql.Connection conExt)
    {
        boolean blnRes=false;
        
        java.sql.Statement stmLoc;
        java.sql.ResultSet rstLoc;
        try{
            if(conExt!=null){
                stmLoc = conExt.createStatement();
                    strSQL ="";
                    strSQL+=" SELECT co_grpInv AS codigo,rtrim(tx_nomGrpInv) AS descripcion FROM tbm_cabGrpInv where st_reg='A' \n";
                    strSQL+=" AND tx_nomGrpInv=" + objUti.codificar(txtNomGrupo.getText()) + "";
                rstLoc = stmLoc.executeQuery(strSQL);
                if(rstLoc.next())
                {
                    estado=1;
                    blnRes=true;
                }
                    
                
                rstLoc.close();
                rstLoc=null;
                stmLoc.close();
                stmLoc=null;
            }
        }
        catch (Exception e) {
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    

    

