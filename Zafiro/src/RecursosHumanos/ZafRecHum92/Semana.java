public class Semana {
    
    
    private int intAnio;
    private int intSemana;
    private String strSemana;
    private String fecDes;
    private String fecHas;

    public int getIntAnio() {
        return intAnio;
    }

    public void setIntAnio(int intAnio) {
        this.intAnio = intAnio;
    }

    public int getIntSemana() {
        return intSemana;
    }

    public void setIntSemana(int intSemana) {
        this.intSemana = intSemana;
    }

    public String getStrSemana() {
        return strSemana;
    }

    public void setStrSemana(String strSemana) {
        this.strSemana = strSemana;
    }

    public String getFecDes() {
        return fecDes;
    }

    public void setFecDes(String fecDes) {
        this.fecDes = fecDes;
    }

    public String getFecHas() {
        return fecHas;
    }

    public void setFecHas(String fecHas) {
        this.fecHas = fecHas;
    }
    
    public String toString() {
        return strSemana;
    }    
    
    
}
