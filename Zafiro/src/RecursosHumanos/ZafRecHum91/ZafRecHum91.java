    private int obtenerEmpresa(int intCodTra){
        Connection con=null;
        Statement stmLocAux=null;
        ResultSet rstEmpTra=null;
        int intCodEmp=0;
        String strSql =  " SELECT zaf.co_tra, zaf.tx_ape, zaf.tx_nom , zaf.co_emp\n" +
                         " FROM ( select a.co_tra,a.tx_ape,a.tx_nom ,b.co_emp\n" +
                         "        from tbm_tra a \n" +
                         "        inner join tbm_traemp b \n" +
                         "        on(a.co_tra=b.co_tra) \n" +
                         "        where b.st_reg like 'A' \n" +
                         "      ) AS zaf \n" +
                         " WHERE LOWER(CAST(zaf.co_tra AS VARCHAR)) LIKE '"+intCodTra+"'";

        try{
            con=DriverManager.getConnection(objParSis.getStringConexion(), objParSis.getUsuarioBaseDatos(),objParSis.getClaveBaseDatos());    
            stmLocAux=con.createStatement();
            rstEmpTra=stmLocAux.executeQuery(strSql);
            if(rstEmpTra.next()){
                intCodEmp=rstEmpTra.getInt("co_emp");
            }
        }catch(SQLException ex){
            ex.printStackTrace();
        }finally{
            try{
                rstEmpTra.close();
                con.close();
                rstEmpTra=null;
                con=null;
            }catch(Exception ex){
                ex.printStackTrace();
            }
        }
        return intCodEmp;
    }
    
