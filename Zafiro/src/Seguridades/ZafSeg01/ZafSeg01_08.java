    private boolean copiarEscritorio(java.sql.Connection conExt, int ROW){
        boolean blnRes=true;
        java.sql.Statement stmLoc;
        java.sql.ResultSet rstLoc;
        int intCodPer=-1;
        try{
            if(conExt!=null){
                stmLoc = conExt.createStatement();
                strSql="";
                strSql+=" SELECT CASE WHEN MAX(co_per) IS NULL THEN 0 ELSE MAX(co_per) END as max ";
                strSql+=" FROM tbm_cabPerUsr ";
                strSql+=" WHERE co_emp="+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_EMP).toString()+" AND co_loc="+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_LOC).toString()+" AND  ";
                strSql+=" co_usr="+txtCodUsr.getText()+" ; ";
                System.out.println("1: " + strSql);
                rstLoc = stmLoc.executeQuery(strSql);
                if(rstLoc.next()){
                    intCodPer = rstLoc.getInt("max");
                }
                rstLoc.close();
                rstLoc = null;
                intCodPer++;
                
                strSql="";
                strSql+=" INSERT INTO tbm_cabPerUsr (co_emp, co_loc, co_usr, co_per, tx_desCor, tx_desLar, st_reg, co_usrIng, fe_ing)  ";
                strSql+=" VALUES ("+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_EMP).toString()+", "+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_LOC).toString()+", "+txtCodUsr.getText()+", ";
                strSql+="  "+intCodPer+", "+objUti.codificar(txtNomEsc.getText(), 1)+", null, 'A' ,"+objParSis.getCodigoUsuario()+",CURRENT_TIMESTAMP ) ";
                System.out.println("2: " + strSql);
                stmLoc.executeUpdate(strSql);
                
                strSql="";
                strSql+=" INSERT INTO tbm_detPerUsr(co_emp, co_loc, co_usr, co_per, co_reg, tx_acc, ne_corX, ne_corY, tx_nom ) \n";
                strSql+=" SELECT "+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_EMP).toString()+" as co_emp, "+tblLoc.getValueAt(ROW,INT_TBL_LOC_COD_LOC).toString()+" as co_loc, \n";
                strSql+="        "+txtCodUsr.getText()+"  as co_usr, "+intCodPer+" as co_per, a.co_reg, a.tx_acc, a.ne_corX, a.ne_corY, a.tx_nom \n";
                strSql+=" FROM (  \n";
                strSql+="   SELECT * FROM tbm_detPerUsr \n";
                strSql+="   WHERE co_emp="+objParSis.getCodigoEmpresa()+" AND co_loc="+objParSis.getCodigoLocal()+" AND  \n";
                strSql+="         co_usr="+objParSis.getCodigoUsuario()+" AND co_per="+txtCodEsc.getText()+" \n";
                strSql+=" ) as a ;  \n";
                System.out.println("3: " + strSql);
                stmLoc.executeUpdate(strSql);
                stmLoc.close();
                stmLoc=null;
            }
        }
        catch (Exception e){
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
    
