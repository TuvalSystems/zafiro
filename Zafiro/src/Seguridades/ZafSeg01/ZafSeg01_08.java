    private boolean guardar(){
        boolean blnRes=false;
        java.sql.Connection conLoc;
        try{
            if(txtCodEsc.getText()!=null){
                if(txtCodEsc.getText().length()>0){
                    if(txtCodUsr.getText()!=null){
                        if(txtCodUsr.getText().length()>0){
                            int intNumFil=objTblModLoc.getRowCountTrue(); 
                            if(objTblModLoc.isCheckedAnyRow(INT_TBL_LOC_CHK)){
                                for (int i=0; i<intNumFil;i++){
                                    if(objTblModLoc.isChecked(i,INT_TBL_LOC_CHK)){
                                        conLoc=DriverManager.getConnection(objParSis.getStringConexion(),objParSis.getUsuarioBaseDatos(),objParSis.getClaveBaseDatos());
                                        if(conLoc!=null){
                                            conLoc.setAutoCommit(false);
                                            if(copiarEscritorio(conLoc, i)){
                                                conLoc.commit();
                                                blnRes=true;
                                            }
                                            conLoc.close();
                                            conLoc=null;
                                        }
                                        
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
        catch (Exception e){
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
