    private boolean cargarPantallas(int CodEmp, int CodLoc, int CodUsr, int CodPer){
        boolean blnRes=true;
        java.sql.Connection conLoc;
        java.sql.Statement stmLoc;
        java.sql.ResultSet rstLoc;
        try{
            conLoc=DriverManager.getConnection(objParSis.getStringConexion(),objParSis.getUsuarioBaseDatos(),objParSis.getClaveBaseDatos());
            if(conLoc!=null){
                stmLoc = conLoc.createStatement();
                strSql="";
                strSql+=" select a1.tx_acc, a1.ne_corX, a1.ne_corY, a1.co_mnu, a2.tx_nom \n";
                strSql+=" from tbm_detPerUsr as a1 ";
                strSql+=" inner join tbm_mnuSis as a2 on (a1.co_mnu=a2.co_mnu)";
                strSql+=" where a1.co_emp="+CodEmp+" and a1.co_loc="+CodLoc+" and a1.co_usr="+CodUsr+" and a1.co_per="+CodPer+" ";
                
                System.out.println("cargarPantallas:... " + strSql);
                rstLoc = stmLoc.executeQuery(strSql);
                while(rstLoc.next()){
                    objParSis.setCodigoMenu(rstLoc.getInt("co_mnu"));
                    objParSis.setNombreMenu(rstLoc.getString("tx_nom"));
                    invocarClase(rstLoc.getString("tx_acc"), rstLoc.getInt("ne_corX"), rstLoc.getInt("ne_corY"));
                }
                rstLoc.close();
                rstLoc=null;
                stmLoc.close();
                stmLoc=null;
                conLoc.close();
                conLoc=null;
            }
        }
        catch(java.sql.SQLException e){
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        catch (Exception e){
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
    
    
