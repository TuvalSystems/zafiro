    private class ZafThreadExe extends Thread
    {
        java.time.LocalDateTime objLocDatTimFecHorSis, objLocDatTimFecHorExe;
        
        public ZafThreadExe()
        {
            //Fecha fija para hacer pruebas.
            //objLocDatTimFecHorExe=java.time.LocalDateTime.of(2020, 6, 26, 17, 31, 30);
            //Ejecutar el siguiente día a las 03:00:00.
            //Ejemplo: Si hoy es 26/Jun/2020 17:15:30 se obtendría 27/Jun/2020 03:00:00
            objLocDatTimFecHorExe=java.time.LocalDate.now().plusDays(1).atStartOfDay().plusHours(3);
        }
        
        public void run()
        {
            try
            {
                //Cerrar Zafiro a las 03:00:00. Menos para el usuario Administrador.
                if (objParSis.getCodigoUsuario()!=1)
                {
                    while (true)
                    {
                        objLocDatTimFecHorSis=java.time.LocalDateTime.now();
                        if (objLocDatTimFecHorExe.isBefore(objLocDatTimFecHorSis))
                        {
                            System.exit(0);
                            break;
                        }
                        try
                        {
                            //Calcular el tiempo a dormir en milisegundos.
                            //La idea es mandar el hilo hasta que le toque cerrar la aplicación para evitar que se esté ejecutando a cada rato innecesariamente.
                            //Lo que normalmente se hace es "sleep(30000);" para que se ejecute cada 30 segundos. Pero eso es ineficiente.
                            System.out.println("Ejecución: " + objLocDatTimFecHorExe);
                            System.out.println("Actual: " + objLocDatTimFecHorSis);
                            long lngTieDor=java.time.Duration.between(objLocDatTimFecHorSis, objLocDatTimFecHorExe).toMillis();
                            System.out.println("Ejecutar en: " + lngTieDor + " milisengundos");
                            sleep(lngTieDor);
                        }
                        catch (InterruptedException e)
                        {
                            System.out.println("Excepción: " + e.toString());
                        }
                    }
                }
            }
            catch (Exception e)
            {
                System.out.println("Excepción: " + e.toString());
            }
        }
    }
    
