    private boolean cargarTblLoc()
    {
        int intCodEmp;
        boolean blnRes=true;
        try
        {
            intCodEmp=objParSis.getCodigoEmpresa();
            con=DriverManager.getConnection(objParSis.getStringConexion(), objParSis.getUsuarioBaseDatos(), objParSis.getClaveBaseDatos());
            if (con!=null)
            {
                stm=con.createStatement();
                //Si es el usuario Administrador (Código=1) tiene acceso a todos los locales.
                if (objParSis.getCodigoUsuario()==1)
                {
                    //Armar la sentencia SQL.
                    strSQL ="";
                    strSQL+=" SELECT a1.co_emp, a1.tx_nom AS tx_nomEmp, a2.co_loc, a2.tx_nom AS tx_nomLoc";
                    //Si la empresa está inactiva se devuelve el estado 'A' para evitar que aparezca marcado en la tabla de locales. 
                    strSQL+=" , (CASE WHEN a1.st_reg='I' THEN 'A' ELSE a2.st_reg END) AS st_reg";
                    strSQL+=" FROM tbm_emp AS a1";
                    strSQL+=" INNER JOIN tbm_loc AS a2 ON (a1.co_emp=a2.co_emp)";
                    if (objParSis.getCodigoEmpresa()!=objParSis.getCodigoEmpresaGrupo())
                    {
                        strSQL+=" WHERE a1.co_emp=" + intCodEmp;
                    }
                    strSQL+=" ORDER BY a1.co_emp, a2.co_loc";
                    rst=stm.executeQuery(strSQL);
                }
                else
                {
                    //Armar la sentencia SQL.
                    strSQL="";
                    strSQL+=" SELECT a2.co_emp, a2.tx_nom AS tx_nomEmp, a3.co_loc, a3.tx_nom AS tx_nomLoc";
                    //Si la empresa está inactiva se devuelve el estado 'A' para evitar que aparezca marcado en la tabla de locales. 
                    strSQL+=" , (CASE WHEN a2.st_reg='I' THEN 'A' ELSE a1.st_reg END) AS st_reg";
                    strSQL+=" FROM tbr_locUsr AS a1";
                    strSQL+=" INNER JOIN tbm_emp AS a2 ON (a1.co_emp=a2.co_emp)";
                    strSQL+=" INNER JOIN tbm_loc AS a3 ON (a1.co_emp=a3.co_emp AND a1.co_loc=a3.co_loc)";
                    strSQL+=" WHERE 1=1";
                    if (objParSis.getCodigoEmpresa()!=objParSis.getCodigoEmpresaGrupo())
                    {
                        strSQL+=" AND a1.co_emp=" + intCodEmp;
                    }
                    strSQL+=" AND a1.co_usr=" + objParSis.getCodigoUsuario();
                    strSQL+=" AND a1.st_reg IN ('A', 'P')";
                    strSQL+=" ORDER BY a1.co_emp, a1.co_loc";
                    rst=stm.executeQuery(strSQL);
                }
                //Limpiar vector de datos.
                vecDat.clear();
                //Obtener los registros.
                while (rst.next())
                {
                    vecReg=new Vector();
                    vecReg.add(INT_TBL_LOC_LIN, "");
                    if (rst.getString("st_reg").equals("P"))
                    {
                        vecReg.add(INT_TBL_LOC_CHK, Boolean.TRUE);
                    }
                    else
                    {
                        vecReg.add(INT_TBL_LOC_CHK, Boolean.FALSE);
                    }
                    vecReg.add(INT_TBL_LOC_COD_EMP, rst.getString("co_emp"));
                    vecReg.add(INT_TBL_LOC_NOM_EMP, rst.getString("tx_nomEmp"));
                    vecReg.add(INT_TBL_LOC_COD_LOC, rst.getString("co_loc"));
                    vecReg.add(INT_TBL_LOC_NOM_LOC, rst.getString("tx_nomLoc"));
                    vecDat.add(vecReg);
                }
                rst.close();
                stm.close();
                con.close();
                rst=null;
                stm=null;
                con=null;
                //Asignar vectores al modelo.
                objTblModLoc.setData(vecDat);
                tblLoc.setModel(objTblModLoc);
                vecDat.clear();
                blnMarTodChkTblLoc=false;
            }
        }
        catch (java.sql.SQLException e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        catch (Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
