    /** Configurar el formulario. */
    private boolean configurarFrm()
    {
        boolean blnRes=true;
        try
        {
            //java.util.Locale.setDefault(java.util.Locale.US);
            java.util.Locale.setDefault(new java.util.Locale("es", "ec"));
            //Si existe una empresa predeterminada ir al "login" caso contrario mostrar ésta ventana.
            if (!objParSis.getEmpresaPredeterminada().equals(""))
            {
                objParSis.setFilaSeleccionada(Integer.parseInt(objParSis.getEmpresaPredeterminada())+1);
                ZafSeg01_01 objSeg=new ZafSeg01_01(objParSis);
                objSeg.setVisible(true);
                this.dispose();
            }
            else
            {
                //Llenar el combo de empresas.
                for (byte i=1;i<objParSis.getNumeroFilas();i++)
                {
                    cboEmp.addItem(objParSis.getNombreEmpresa(i));
                }
            }
        }
        catch (Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
    /**
     * Esta función avanza a la siguiente ventana automáticamente. Cuando la clase recibe 5 parámetros por consola (Indice de la conexión
     * , código de la empresa, código del local, usuario y contraseña) avanza automáticamente a la siguiente ventana (ZafSeg01_01).
     * @return true: Si se pudo ejecutar la función con éxito.
     * <BR>false: En el caso contrario.
     */
    private boolean avanzarSigVen()
    {
        boolean blnRes=true;
        int i;
        try
        {
            //Buscar y seleccionar la empresa por la que se debe ingresar.
            for (i=1; i<objParSis.getNumeroFilas(); i++)
            {
                try
                {
                    if (objParSis.getStringConexion(i).equals(objParSis.getStringConexion(Integer.parseInt(strParRecCon[0]))) && objParSis.getCodigoEmpresa(i)==Integer.parseInt(strParRecCon[1]))
                    {
                        cboEmp.setSelectedIndex(i-1);
                        break;
                    }
                }
                catch (NumberFormatException e)
                {
                    //En el Servidor de Desarrollo se sabe ubicar una fila en blanco como un separador. Es decir, la fila tiene sus valores en NULL.
                    //Al llegar a la fila en blanco se generaba una excepción al utilizar "objParSis.getCodigoEmpresa(i)" porque el código de empresa tenía NULL.
                    //Eso hacía que se generara un excepción y terminara la búsqueda sin llegar el final. Por ese motivo se tuvo que poner otro try-catch dentro
                    //del try-catch existente. Es decir, de forma anidada. En el catch interno no se puso código porque la idea de dicho catch es que si se genera
                    //una excepción se continue con la búsqueda.
                }
            }
            if (i<objParSis.getNumeroFilas())
            {
                butAceActionPerformed(null);
            }
            else
            {
                this.setVisible(false);
                javax.swing.JOptionPane.showMessageDialog(this, "Ocurrió un error al abrir la empresa en el Sistema Zafiro.\nEl error se presenta porque la empresa no está agregada en el listado de empresas.\nNotifíquelo a su administrador del Sistema para que la agregue.\nCódigo de la empresa a agregar: " + strParRecCon[1], "Mensaje del sistema Zafiro", javax.swing.JOptionPane.ERROR_MESSAGE);
                System.exit(0);
            }
        }
        catch (Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
