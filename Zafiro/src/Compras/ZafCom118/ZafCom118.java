                        vecReg.add(INT_TBL_DAT_CIU_CLI, rstLoc.getString("CLI_SUC_CIUDAD"));
                        
                        
                        vecReg.add(INT_TBL_DAT_BOD, rstLoc.getString("BODEGA"));
