    private boolean consultar_BodegaUbicacion(java.sql.Connection conExt)
    {
        boolean blnRes=false;
        
        java.sql.Statement stmLoc;
        java.sql.ResultSet rstLoc;
        try{
            if(conExt!=null){
                stmLoc = conExt.createStatement();
                strSQL="";
                strSQL+=" SELECT * FROM TUVAL..IV40701 where LOCNCODE='"+txtBodega.getText()+"' AND BIN='"+txNueUbica.getText()+"' ";
                rstLoc = stmLoc.executeQuery(strSQL);
                if(rstLoc.next())
                {
                    estado=1;
                    blnRes=true;
                }
                    
                
                rstLoc.close();
                rstLoc=null;
                stmLoc.close();
                stmLoc=null;
            }
        }
        catch (Exception e) {
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
