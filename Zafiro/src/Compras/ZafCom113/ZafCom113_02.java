    /**
     * Funcion para saber si el dato ingresado es un nuemero 
     * @param texto
     * @return 
     */
    private boolean esNumero(String texto) {
        boolean blnRes=false;
        try {
            Double.parseDouble(texto);
            blnRes= true;
        } catch (NumberFormatException e) {
            System.out.println("NO ES NUMERO " + e.toString());
            blnRes=false;
        }
        return blnRes;
    }

    
    
    
