    /** Configurar el formulario. */
    private boolean configurarFrm(){
        boolean blnRes=true;
        try{
             
            //Inicializar objetos.
            objUti=new ZafUtil(); 
            strAux=objParSis.getNombreMenu();
            this.setTitle(strAux + strVersion);
            lblTit.setText(strAux);
             
            
            dtpFecDoc = new ZafDatePicker(javax.swing.JOptionPane.getFrameForComponent(this), "d/m/y");
            dtpFecDoc.setBackground(objParSis.getColorCamposObligatorios());
            dtpFecDoc.setText("");
            panFil.add(dtpFecDoc);
            dtpFecDoc.setBounds(550, 6, 120, 20);
             
            txtNumDoc.setBackground(objParSis.getColorCamposObligatorios());
            txtCliCod.setBackground(objParSis.getColorCamposObligatorios());
            txtCliNom.setBackground(objParSis.getColorCamposObligatorios());
            txtCodUsr.setBackground(objParSis.getColorCamposObligatorios()); 
            txtNomUsr.setBackground(objParSis.getColorCamposObligatorios());
             
            configurarTblDat();
            configurarVenConClientes();
            configurarVenConVendedor();
            
            objTooBar=new MiToolBar(this);
            panBar.add(objTooBar);
            
           
        }
        catch(Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
    
    
    
