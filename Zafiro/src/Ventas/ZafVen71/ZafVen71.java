    /** Configurar el formulario. */
    private boolean configurarFrm()
    {
        boolean blnRes=true;
        try{
            //Inicializar objetos.
            objUti=new ZafUtil();
            //Obbtener los permisos del usuario.
            objPerUsr=new ZafPerUsr(objParSis);
            strAux=objParSis.getNombreMenu();
            this.setTitle(strAux + strVersion);
            lblTit.setText(strAux);
            configurarTblDat();
            cargarComboAnios();
        }
        catch(Exception e)
        {
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }

    
    private boolean cargarComboAnios(){
        boolean blnRes=true;
        try{
            int intArrItems[];
            intArrItems = objParSis.getAniosCreadosSistema();            
            cboAnio.removeAllItems();
            for(int i=0;i<intArrItems.length;i++){
                cboAnio.addItem(String.valueOf(intArrItems[i]));
            }
            cboAnio.setSelectedIndex(intArrItems.length-1);
        }
        catch(Exception e){
            blnRes=false;
            objUti.mostrarMsgErr_F1(this, e);
        }
        return blnRes;
    }
     
    
