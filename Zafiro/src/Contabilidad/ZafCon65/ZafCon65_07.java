    private void btnGuardaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardaActionPerformed
        // TODO add your handling code here:
       //validar campos obligatorios  
       boolean blnRes = true;
       int coreg =0;
       strSqlIns="";
        movimientos = new ArrayList<>();  
       
        for (int i = 0; i < objTblModExc.getRowCountTrue(); i++) {
           coreg+=1;
           Object objmnto = objTblModExc.getValueAt(i, INT_DAT_MNT);
           String mnto = (objmnto != null) ? objmnto.toString() : ""; 
           
           Object objobservacion = objTblModExc.getValueAt(i, INT_DAT_OBS);
           String observacion = (objobservacion != null) ? objobservacion.toString() : ""; 
           
           Object objnomcta = objTblModExc.getValueAt(i, INT_DAT_CTA);
           String nomcta = (objnomcta != null) ? objnomcta.toString() : ""; 
           
           Object objTipmov = objTblModExc.getValueAt(i, INT_DAT_TIP_MOV);
           String Tipmov = (objTipmov != null) ? objTipmov.toString() : ""; 
         
               if (nomcta.equals("")){  
                   mostrarMsgErr("Seleccione una cuenta para el valor ingresado");
                   blnRes=false;
                   continue;
               }
               if (mnto.equals("")){  
                   mostrarMsgErr("Seleccione una valor para el cuenta " +nomcta );
                   blnRes=false;
                   continue;
               }
               if (Tipmov.equals("")){  
                   mostrarMsgErr("Seleccione el tipo de movimiento para la cuenta "+nomcta);
                   blnRes=false;
                   continue;
               }
               if (observacion.equals("")){  
                   mostrarMsgErr("Ingrese una observacion para la cuenta "+nomcta);  
                   blnRes=false;
                   continue;
               }
               //obtener el #de cuenta
               String IntCodCta="";
               int index = nomcta.indexOf('-');
               if (index != -1) {
                   IntCodCta = nomcta.substring(0, index);
               }
               String strTipmov="";
               if (Tipmov.equals("Debe")){
                   strTipmov="D";
               }else if (Tipmov.equals("Haber")){
                   strTipmov="H";                                  
               }
               strSqlIns+=" insert into tbm_detotrdes (co_emp,co_per,ne_per,co_tra,co_reg,co_cta,tx_tipmov,tx_obs,nd_mntcta)values(1," +
                       CodPeriodo+","+ strNePeri+ "," + strcotra+ "," + coreg + "," + IntCodCta+ ",'"+ strTipmov+ "','" + observacion + "',"+mnto+ ");"; 
               
               DetalleRol movimiento = new DetalleRol(
                    1, // coEmp
                    Integer.parseInt(CodPeriodo),
                    Integer.parseInt(strNePeri),
                    strcotra,
                    coreg,
                    IntCodCta,
                    strTipmov,
                    observacion,
                    Double.parseDouble(mnto) 
               );

            movimientos.add(movimiento);
               
        }
        //validar totales 
        if (blnRes){
          for (int i = 0; i < objTblTot.getRowCountTrue(); i++) {
              Object objtotales = objTblTot.getValueAt(i, 2);
               String valorTot = (objtotales != null) ? objtotales.toString() : ""; 
               valorTotal  = Double.parseDouble(valorTot); // Convertir a double
               if (valorTotal != dblValTotEx){ 
                   mostrarMsgErr("Hay un descuadre de valores entre el total y su detalle. Favor corregir y volver a intentar");
               }else{
                   if(!strSqlIns.equals("")){ 
                       blnAcepta=true;
                   }
               }   
          }
          this.setVisible(false);
        }
        
        
        
    }//GEN-LAST:event_btnGuardaActionPerformed
    
