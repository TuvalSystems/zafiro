        private boolean cargarReg(Double douValor, String strCodPeriodo, String strNePer,Integer codTra,List<DetalleRol> ListdetTra) {
        java.sql.Connection con = null;
        java.sql.Statement stm = null;
        java.sql.ResultSet rst = null;
        String strSql = "";
        boolean blnRes = true;  
        int i;
        String IntCodCta="", item="";

        try {
            con= DriverManager.getConnection(objParSis.getStringConexion_Dynamics2021(),objParSis.getUsuarioBaseDatos_Dynamics2021(),objParSis.getClaveBaseDatos_Dynamics2021());
            vecDat = new Vector();

            if (con != null) {
                stm = con.createStatement(); 
                strSql = "";      
                strSql += "  select co_reg,tx_tipmov,tx_obs,nd_mntcta,co_cta from tbm_cabotrdes a  inner join tbm_detotrdes b  on a.co_emp=b.co_emp and a.co_per=b.co_per and a.ne_per=b.ne_per and a.co_tra=b.co_tra where a.co_emp=1 and a.ne_per=" + strNePer + " and a.co_per=" + strCodPeriodo + " and a.co_tra=" +  codTra;
                rst = stm.executeQuery(strSql);

                vecDat.clear(); 
                i = 0;
                   if (rst.next()) {
                   //vecDat = new Vector();
                    do {
                        vecReg = new Vector();
                        vecReg.add(INT_TBL_DAT_LINEA, "");
                        //vecReg.add(INT_DAT_CTA,rst.getString("co_cta"));
                          for (i=0;i<objTblCelEdiCmbBox1.getItemCount();i++){
                                        
                                        item= objTblCelEdiCmbBox1.getItemAt(i).toString();  
                                         int index = item.indexOf('-');   
                                         if (index != -1) {
                                             IntCodCta = item.substring(0, index);
                                           if(IntCodCta.equals(rst.getString("co_cta"))){
                                               //System.out.println("si lo encuentra.... ");
                                               vecReg.add(INT_DAT_CTA,item);
                                               break;
                                           }
                                       }
                                    } 
                       
                        vecReg.add(INT_DAT_MNT, rst.getString("nd_mntcta"));   
                        if (rst.getString("tx_tipmov").equals("D") ){
                            vecReg.add(INT_DAT_TIP_MOV,"Debe");
                        }
                        else if (rst.getString("tx_tipmov").equals("H") ){
                            vecReg.add(INT_DAT_TIP_MOV,"Haber");
                        }
                    
                        vecReg.add(INT_DAT_OBS, rst.getString("tx_obs")); 
                        vecDat.add(vecReg);
                        i++;
                    } while (rst.next());
                }else{
                       if (ListdetTra.size() >0){
                               for (int j = 0; j < ListdetTra.size(); j++) {
                                   DetalleRol detalle = ListdetTra.get(j); 
                                   String coCta = detalle.getCoCta();      
                                   String tipMovi = detalle.getTxTipMov();
                                   Double monto = detalle.getNdMntCta();
                                   String observ = detalle.getTxObs();
                                   
                                   vecReg = new Vector();  
                                   vecReg.add(INT_TBL_DAT_LINEA, "");
//                                   vecReg.add(INT_DAT_CTA,item);
                                   for (i=0;i<objTblCelEdiCmbBox1.getItemCount();i++){
                                        
                                        item= objTblCelEdiCmbBox1.getItemAt(i).toString();  
                                        
                                         int index = item.indexOf('-');   
                                         if (index != -1) {
                                             IntCodCta = item.substring(0, index);
                                           if(IntCodCta.equals(coCta)){
                                               //System.out.println("si lo encuentra.... ");
                                               vecReg.add(INT_DAT_CTA,item);
                                               break;
                                           }
                                       }
                                    }  
                                   
                                    vecReg.add(INT_DAT_MNT, monto); 
                                    
                                    if (tipMovi.equals("D") ){
                                        vecReg.add(INT_DAT_TIP_MOV,"Debe");
                                    }
                                    else if (tipMovi.equals("H") ){
                                        vecReg.add(INT_DAT_TIP_MOV,"Haber");
                                    }
                                    vecReg.add(INT_DAT_OBS,observ); 
                                    vecDat.add(vecReg);  
                                   // System.out.println("VecDat " + vecDat.toString());
                               }
                               
                       }else{
                        
                       vecReg = new Vector();  
                       vecReg.add(INT_TBL_DAT_LINEA, "");
                       vecReg.add(INT_DAT_CTA,"");
                       vecReg.add(INT_DAT_MNT, douValor);   
                       vecReg.add(INT_DAT_TIP_MOV, "");
                       vecReg.add(INT_DAT_OBS,""); 
                       vecDat.add(vecReg);  
                       }                    
                   }                         
                }
           // System.out.println("VecDat2  " + vecDat.toString());
                //Asignar vectores al modelo.
                objTblModExc.setData(vecDat);
                tbDatos.setModel(objTblModExc);   
                objTblTot.calcularTotales();   
                con.close();
                con = null;
          
        } catch (Exception e) {
            blnRes = false;
        }
        return blnRes;
    }
    
    
