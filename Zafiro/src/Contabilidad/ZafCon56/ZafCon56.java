    private void butConActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_butConActionPerformed
        
        String strAuxLoc;
            
        if (objTblModMesCom.getRowCountChecked(INT_TBL_DAT_MES_CHK) == 0)
        {  strAuxLoc =  "<HTML>No está seleccionado ningún mes en la tabla <FONT COLOR=\"blue\">Meses a comparar</FONT>.<BR>";
           strAuxLoc += "Seleccione al menos algún mes y vuelva a intentarlo.</HTML>";
           mostrarMsgInf(strAuxLoc);
           return;
        }

        //Realizar accián de acuerdo a la etiqueta del botán ("Consultar" o "Detener").
        if (butCon.getText().equals("Consultar"))
        {
            blnCon=true;
            if (objThrGUI==null)
            {
                objThrGUI=new ZafThreadGUI();
                objThrGUI.start();
            }            
        }
        else
        {
            blnCon=false;
        }
    }//GEN-LAST:event_butConActionPerformed

