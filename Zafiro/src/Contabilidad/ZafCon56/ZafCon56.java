    /**
     * Esta función se ejecuta cuando se hace el "MouseClicked" en la cabecera del JTable.
     * Se utiliza ésta función especificamente para marcar todas las casillas de verificación
     * de la columna "Sel.".
     */
    private void tblDatMouseClicked(java.awt.event.MouseEvent evt)
    {
        int i, intNumFil;
        try
        {
            intNumFil = objTblModMesCom.getRowCountTrue();
            //Marcar la casilla solo si se da 1 click con el boton izquierdo.
            if (evt.getButton()==evt.BUTTON1 && evt.getClickCount()==1 && tblMesCom.columnAtPoint(evt.getPoint())==INT_TBL_DAT_MES_CHK)
            {
                if (blnMarTodChkTblMesCom)
                {
                    for (i=0; i<intNumFil; i++)
                    {
                        objTblModMesCom.setChecked(true, i, INT_TBL_DAT_MES_CHK);
                    }
                    blnMarTodChkTblMesCom=false;
                }
                else
                {
                    for (i=0; i<intNumFil; i++)
                    {
                        objTblModMesCom.setChecked(false, i, INT_TBL_DAT_MES_CHK);
                    }
                    blnMarTodChkTblMesCom=true;
                }
            }
        }
        catch (Exception e)
        {
            objUti.mostrarMsgErr_F1(this, e);
        }
    } //Funcion tblDatMouseClicked()
